var ascensionSkillPercent = 0;
var ascensionStatPercent = 0;
var ascensionPoints = 0;
var ascensionUpgrades = {
    dankNullSpace: 0,
    megagrid: 0,
    wonderland: 0,
    photosynthesis: 0,
    spookyTravel: 0,
    ethernalSmuggling: 0,
};
var playerDeathInProgress = false;

function loadAscensionProgress() {
    try {
        const raw = localStorage.getItem(ASCENSION_STORAGE_KEY);
        if (!raw) return;
        const saved = JSON.parse(raw);
        ascensionSkillPercent = Math.max(0, Number(saved.skillPercent) || 0);
        ascensionStatPercent = Math.max(0, Number(saved.statPercent) || 0);
        ascensionPoints = Math.max(0, Math.floor(Number(saved.points) || 0));
        const upgrades = saved.upgrades && typeof saved.upgrades === "object"
            ? saved.upgrades
            : {};
        ascensionUpgrades = {
            dankNullSpace: Math.max(0, Math.floor(Number(upgrades.dankNullSpace) || 0)),
            megagrid: Math.max(0, Math.floor(Number(upgrades.megagrid) || 0)),
            wonderland: Math.max(0, Math.floor(Number(upgrades.wonderland) || 0)),
            photosynthesis: Math.max(0, Math.floor(Number(upgrades.photosynthesis) || 0)),
            spookyTravel: Math.max(0, Math.floor(Number(upgrades.spookyTravel) || 0)),
            ethernalSmuggling: Math.max(0, Math.floor(Number(upgrades.ethernalSmuggling) || 0)),
        };
    } catch (error) {
        ascensionSkillPercent = 0;
        ascensionStatPercent = 0;
        ascensionPoints = 0;
        ascensionUpgrades = {
            dankNullSpace: 0,
            megagrid: 0,
            wonderland: 0,
            photosynthesis: 0,
            ethernalSmuggling: 0,
        };
    }
}

function saveAscensionProgress() {
    try {
        localStorage.setItem(ASCENSION_STORAGE_KEY, JSON.stringify({
            skillPercent: ascensionSkillPercent,
            statPercent: ascensionStatPercent,
            points: ascensionPoints,
            upgrades: Object.assign({}, ascensionUpgrades),
        }));
    } catch (error) {
        // A blocked storage must not prevent the run from ending.
    }
}

function getAscensionMultiplier(type) {
    const percent = type === "stat"
        ? ascensionStatPercent
        : ascensionSkillPercent;
    return 1 + Math.max(0, Number(percent) || 0) / PERCENT;
}

function getAscensionTotals() {
    let skillLevels = 0;
    let statLevels = 0;

    if (player) {
        LEARNABLE_SKILL_KEYS.forEach(function (key) {
            const skill = player[key];
            if (skill && Number.isFinite(Number(skill.lvl))) {
                skillLevels += Math.max(0, Number(skill.lvl));
            }
        });
        CORE_STAT_NAMES.forEach(function (key) {
            const stat = player[key];
            if (stat && Number.isFinite(Number(stat.lvl))) {
                statLevels += Math.max(0, Number(stat.lvl));
            }
        });
    }

    return { skillLevels: skillLevels, statLevels: statLevels };
}

function getIngameDaysSurvived() {
    if (typeof gameTime === "undefined"
        || typeof GAME_MINUTES_PER_DAY === "undefined") {
        return 0;
    }
    const totalMinutes = Math.max(0, Number(gameTime.totalMinutes) || 0);
    const startMinutes = typeof GAME_START_TOTAL_MINUTES !== "undefined"
        ? Number(GAME_START_TOTAL_MINUTES) || 0
        : 0;
    return Math.max(0, (totalMinutes - startMinutes) / GAME_MINUTES_PER_DAY);
}

// Character points = (1 + characterLevel / 10)
//   * sqrt((skillLevels + statLevels) * (1 + survivedDays)).
function calculateAscensionPoints() {
    const totals = getAscensionTotals();
    const totalLevels = totals.skillLevels + totals.statLevels;
    const days = getIngameDaysSurvived();
    const level = Math.max(1, Number(player && player.lvl) || 1);
    return Math.max(0, Math.floor(
        (1 + level / 10) * Math.sqrt(totalLevels * (1 + days))
    ));
}

function recordAscensionFromCurrentRun() {
    const totals = getAscensionTotals();
    ascensionSkillPercent += totals.skillLevels;
    ascensionStatPercent += totals.statLevels;
    return totals;
}

function updateAscensionMultiplierDisplay() {
    const element = document.getElementById("ascensionmultiplier");
    if (!element) return;
    const format = typeof round2 === "function"
        ? round2
        : function (value) { return Math.round(Number(value) * 100) / 100; };
    element.innerText = "ascensionMultiplier: skills ×"
        + format(getAscensionMultiplier("skill"))
        + ", stats ×" + format(getAscensionMultiplier("stat"))
        + " (+" + format(ascensionSkillPercent)
        + "% / +" + format(ascensionStatPercent) + "%)";
    element.setAttribute(
        "data-tooltip",
        "Permanent rebirth bonus. Each skill or stat level at death adds 1% "
        + "to that category's experience growth."
    );
}

function getAscensionUpgradeDefinition(id) {
    return ASCENSION_UPGRADE_DEFS.find(function (upgrade) {
        return upgrade.id === id;
    }) || null;
}

function getAscensionUpgradeLevel(id) {
    return Math.max(0, Math.floor(Number(ascensionUpgrades[id]) || 0));
}

function getWonderlandSleepMultiplier() {
    return Math.pow(1.2, getAscensionUpgradeLevel("wonderland"));
}

function getPhotosynthesisLevel() {
    return getAscensionUpgradeLevel("photosynthesis");
}

function getSpookyTravelLevel() {
    return getAscensionUpgradeLevel("spookyTravel");
}

function getSpookyTravelMobLevelMultiplier() {
    return 1 + getSpookyTravelLevel();
}

const SMUGGLED_ITEM_STORAGE_KEY = "muuguu_smuggled_item";
const NEXT_WORLD_SEED_KEY = "muuguu_next_seed";

function getInventoryItemEntries() {
    if (!player || !Array.isArray(player.equipinventory)) return [];
    return player.equipinventory.map(function (item, index) {
        return item ? { item: item, index: index } : null;
    }).filter(Boolean);
}

function applySmuggledItem() {
    try {
        const raw = localStorage.getItem(SMUGGLED_ITEM_STORAGE_KEY);
        if (!raw) return;
        const saved = JSON.parse(raw);
        const item = typeof restoreItemInstance === "function"
            ? restoreItemInstance(saved)
            : null;
        if (!item || !player || !Array.isArray(player.equipinventory)) {
            localStorage.removeItem(SMUGGLED_ITEM_STORAGE_KEY);
            return;
        }
        const emptyIndex = player.equipinventory.indexOf(null);
        if (emptyIndex !== -1) {
            player.equipinventory[emptyIndex] = item;
        }
        localStorage.removeItem(SMUGGLED_ITEM_STORAGE_KEY);
    } catch (error) {
        // A malformed transfer is simply discarded.
    }
}

function queueNextWorldSeed() {
    try {
        const current = window.mapView && typeof window.mapView.getSeed === "function"
            ? Number(window.mapView.getSeed())
            : Number(window.pendingMapSeed);
        let next = Math.floor(Math.random() * 1000000);
        while (Number.isFinite(current) && next === current) {
            next = Math.floor(Math.random() * 1000000);
        }
        localStorage.setItem(NEXT_WORLD_SEED_KEY, String(next));
    } catch (error) {
        // The new page still generates a random seed when storage is blocked.
    }
}

function showSmuggleSelection(cause) {
    if (document.getElementById("smuggleoverlay")) return;
    const entries = getInventoryItemEntries();
    if (!entries.length) {
        showLimbo(cause);
        return;
    }

    const overlay = document.createElement("div");
    overlay.id = "smuggleoverlay";
    overlay.className = "limbo smuggleoverlay";

    const title = document.createElement("div");
    title.className = "limbo-title";
    title.innerText = "SMUGGLE ONE ITEM";
    overlay.appendChild(title);

    const subtitle = document.createElement("div");
    subtitle.className = "limbo-cause";
    subtitle.innerText = "Choose one item to carry into the new world.";
    overlay.appendChild(subtitle);

    const list = document.createElement("div");
    list.className = "smuggle-list";
    let selectedIndex = null;

    entries.forEach(function (entry) {
        const item = entry.item;
        const button = document.createElement("button");
        button.type = "button";
        button.className = "smuggle-item";
        const name = typeof getInventoryItemName === "function"
            ? getInventoryItemName(item)
            : "item";
        const rarity = typeof getItemRarityId === "function"
            ? getItemRarityId(item)
            : null;
        const rarityLabel = rarity && typeof getRarityLabel === "function"
            ? getRarityLabel(rarity)
            : "";
        button.innerText = name
            + " | Q" + (Number(item.quality) || 1)
            + (rarityLabel ? " | " + rarityLabel : "");
        button.addEventListener("click", function () {
            selectedIndex = entry.index;
            Array.prototype.forEach.call(list.children, function (child) {
                child.classList.toggle("selected", child === button);
            });
            smuggleButton.disabled = false;
        });
        list.appendChild(button);
    });

    overlay.appendChild(list);

    const footer = document.createElement("div");
    footer.className = "smuggle-footer";

    const skipButton = document.createElement("button");
    skipButton.type = "button";
    skipButton.className = "limboreborn";
    skipButton.innerText = "skip";
    skipButton.addEventListener("click", function () {
        overlay.remove();
        showLimbo(cause);
    });
    footer.appendChild(skipButton);

    const smuggleButton = document.createElement("button");
    smuggleButton.type = "button";
    smuggleButton.className = "limboreborn";
    smuggleButton.innerText = "smuggle";
    smuggleButton.disabled = true;
    smuggleButton.addEventListener("click", function () {
        if (selectedIndex == null) return;
        const item = player.equipinventory[selectedIndex];
        if (!item) return;
        try {
            localStorage.setItem(
                SMUGGLED_ITEM_STORAGE_KEY,
                JSON.stringify(item)
            );
        } catch (error) {
            // The run continues without a transfer if storage is blocked.
        }
        overlay.remove();
        showLimbo(cause);
    });
    footer.appendChild(smuggleButton);
    overlay.appendChild(footer);

    document.body.appendChild(overlay);
}

function getAscensionUpgradeCost(id) {
    const definition = getAscensionUpgradeDefinition(id);
    if (!definition) return Infinity;
    const level = getAscensionUpgradeLevel(id);
    const raw = definition.costPerLevel != null
        ? definition.baseCost + definition.costPerLevel * level
        : definition.baseCost * Math.pow(definition.costGrowth, level);
    // Avoid floating-point noise making an exact cost one point too high.
    return Math.ceil(raw - 1e-9);
}

function buyAscensionUpgrade(id) {
    const definition = getAscensionUpgradeDefinition(id);
    if (!definition) return false;
    const cost = getAscensionUpgradeCost(id);
    if (ascensionPoints < cost) return false;

    ascensionPoints -= cost;
    ascensionUpgrades[id] = getAscensionUpgradeLevel(id) + 1;
    saveAscensionProgress();
    return true;
}

function renderLimboShop(limbo) {
    if (!limbo) return;
    const oldShop = limbo.querySelector(".limbo-shop");
    if (oldShop) oldShop.remove();

    const points = limbo.querySelector("#limbopoints");
    if (points) points.innerText = "Ascension points: " + ascensionPoints;

    const shop = document.createElement("div");
    shop.className = "limbo-shop";

    ASCENSION_UPGRADE_DEFS.forEach(function (definition) {
        const level = getAscensionUpgradeLevel(definition.id);
        const cost = getAscensionUpgradeCost(definition.id);
        const row = document.createElement("div");
        row.className = "limbo-upgrade";

        const heading = document.createElement("div");
        heading.className = "limbo-upgrade-heading";
        heading.innerText = definition.name + " — level " + level;
        row.appendChild(heading);

        const description = document.createElement("div");
        description.className = "limbo-upgrade-description";
        description.innerText = definition.description;
        row.appendChild(description);

        const footer = document.createElement("div");
        footer.className = "limbo-upgrade-footer";
        const price = document.createElement("span");
        price.className = "limbo-upgrade-cost";
        price.innerText = cost + " AP";
        footer.appendChild(price);

        const button = document.createElement("button");
        button.type = "button";
        button.className = "limbo-upgrade-button";
        button.innerText = "Buy";
        button.disabled = ascensionPoints < cost;
        button.addEventListener("click", function () {
            if (buyAscensionUpgrade(definition.id)) {
                renderLimboShop(limbo);
            }
        });
        footer.appendChild(button);
        row.appendChild(footer);

        shop.appendChild(row);
    });

    const empty = limbo.querySelector(".limbo-empty");
    if (empty && empty.parentNode === limbo) {
        limbo.insertBefore(shop, empty);
    } else {
        limbo.appendChild(shop);
    }
}

function showLimbo(cause) {
    if (document.getElementById("limbo")) return;

    const limbo = document.createElement("div");
    limbo.id = "limbo";
    limbo.className = "limbo";

    const stars = document.createElement("div");
    stars.className = "limbo-stars";
    limbo.appendChild(stars);

    const title = document.createElement("div");
    title.className = "limbo-title";
    title.innerText = "LIMBO";
    limbo.appendChild(title);

    const points = document.createElement("div");
    points.id = "limbopoints";
    points.className = "limbo-points";
    points.innerText = "Ascension points: " + ascensionPoints;
    limbo.appendChild(points);

    const causeText = document.createElement("div");
    causeText.id = "limbocause";
    causeText.className = "limbo-cause";
    causeText.innerText = cause || "Your body gave out.";
    limbo.appendChild(causeText);

    const emptySpace = document.createElement("div");
    emptySpace.className = "limbo-empty";
    limbo.appendChild(emptySpace);

    renderLimboShop(limbo);

    const rebornButton = document.createElement("button");
    rebornButton.type = "button";
    rebornButton.id = "limboreborn";
    rebornButton.className = "limboreborn";
    rebornButton.innerText = "reborn";
    rebornButton.addEventListener("click", function () {
        rebornButton.disabled = true;
        if (typeof resetGameTime === "function") resetGameTime();
        queueNextWorldSeed();
        window.location.reload();
    });
    limbo.appendChild(rebornButton);

    document.body.appendChild(limbo);
}

function checkPlayerDeath(cause) {
    if (playerDeathInProgress || !player || player.hp > 0) return false;

    playerDeathInProgress = true;
    const totals = recordAscensionFromCurrentRun();
    const pointsEarned = calculateAscensionPoints();
    ascensionPoints += pointsEarned;
    saveAscensionProgress();
    if (typeof logMessage === "function") {
        logMessage("You died. Your knowledge ascends: +"
            + totals.skillLevels + "% skill growth, +"
            + totals.statLevels + "% stat growth, +"
            + pointsEarned + " Ascension points.");
    }
    updateAscensionMultiplierDisplay();
    if (getAscensionUpgradeLevel("ethernalSmuggling") > 0
        && getInventoryItemEntries().length > 0) {
        showSmuggleSelection(cause);
    } else {
        showLimbo(cause);
    }
    return true;
}

